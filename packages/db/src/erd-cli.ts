import { writeFileSync } from 'node:fs';
import postgres from 'postgres';

/**
 * Writes docs/database.md: every table with its columns, and a Mermaid entity-relationship diagram from the real foreign keys.
 * Run against a migrated database:  MIGRATE_DATABASE_URL=... pnpm --filter @kora/db erd
 */
const url = process.env.MIGRATE_DATABASE_URL ?? process.env.DATABASE_URL;
if (!url) throw new Error('Set MIGRATE_DATABASE_URL');
const sql = postgres(url, { max: 1, onnotice: () => {} });

const cols = await sql`select c.table_name, c.column_name, c.data_type, c.is_nullable, c.column_default
                         from information_schema.columns c join information_schema.tables t on t.table_name = c.table_name and t.table_schema = c.table_schema
                        where c.table_schema = 'public' and t.table_type = 'BASE TABLE' order by c.table_name, c.ordinal_position`;
const pks = await sql`select tc.table_name, kcu.column_name from information_schema.table_constraints tc
                        join information_schema.key_column_usage kcu on kcu.constraint_name = tc.constraint_name and kcu.table_schema = tc.table_schema
                       where tc.table_schema = 'public' and tc.constraint_type = 'PRIMARY KEY'`;
const fks = await sql`select conrelid::regclass::text as child, confrelid::regclass::text as parent, conname
                        from pg_constraint where contype = 'f' and connamespace = 'public'::regnamespace order by 1, 2`;
const rls = await sql`select relname, relrowsecurity from pg_class where relnamespace = 'public'::regnamespace and relkind = 'r'`;
await sql.end();

const pk = new Set(pks.map((r) => `${r.table_name}.${r.column_name}`));
const secured = new Set(rls.filter((r) => r.relrowsecurity).map((r) => r.relname as string));
const tables = [...new Set(cols.map((c) => c.table_name as string))];
const rel = [...new Set(fks.map((f) => `${f.parent} ||--o{ ${f.child} : ""`))];

let md = `# Database\n\nGenerated by \`pnpm --filter @kora/db erd\` from the migrated schema. Do not edit by hand.\n\n`;
md += `${tables.length} tables. ${tables.filter((t) => secured.has(t)).length} have row-level security, which is how one business is kept away from another.\n\n`;
md += '```mermaid\nerDiagram\n' + rel.map((r) => `  ${r}`).join('\n') + '\n```\n\n';
for (const t of tables) {
  md += `## ${t}${secured.has(t) ? ' (row-level security)' : ''}\n\n| column | type | null | default |\n|---|---|---|---|\n`;
  for (const c of cols.filter((x) => x.table_name === t)) md += `| ${pk.has(`${t}.${c.column_name}`) ? '**' + c.column_name + '**' : c.column_name} | ${c.data_type} | ${c.is_nullable === 'YES' ? 'yes' : ''} | ${c.column_default ? String(c.column_default).replace(/\|/g, '\|').slice(0, 50) : ''} |\n`;
  md += '\n';
}
writeFileSync(new URL('../../../docs/database.md', import.meta.url), md);
console.log(`wrote docs/database.md (${tables.length} tables)`);
