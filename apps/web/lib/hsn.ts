/** Matches the words typed against the description and the start of the code. Returns the best few. */
export function searchHsn(q: string, limit = 8): HsnEntry[] {
  const t = q.trim().toLowerCase();
  if (!t) return [];
  const words = t.split(/\s+/);
  return HSN_LIST.filter((e) => words.every((w) => e.text.toLowerCase().includes(w) || e.code.startsWith(w))).slice(0, limit);
}
